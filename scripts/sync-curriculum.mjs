import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const sourceRoot = process.argv[2] ? resolve(process.argv[2]) : null;

if (!sourceRoot) {
  console.error("Usage: node scripts/sync-curriculum.mjs <korean-secondary-learning-map checkout>");
  process.exit(1);
}

const readCollection = (level, name) =>
  JSON.parse(readFileSync(resolve(sourceRoot, "data", "kr", level, `${name}.json`), "utf8"));

const categoryLabels = {
  common: "공통",
  "middle-elective": "중학교 선택",
  "general-elective": "일반 선택",
  "career-elective": "진로 선택",
  "convergence-elective": "융합 선택",
  "specialized-common": "전문 교과 공통",
  "major-general": "전문 교과 일반",
  "major-practical": "전문 교과 실무",
};

const collator = new Intl.Collator("ko-KR");
const releases = {};
const courses = [];
const officialContent = JSON.parse(readFileSync(resolve("sources", "ncic", "content-elements.json"), "utf8"));
const officialByCourse = new Map(officialContent.courses.map((course) => [course.id, course.elements]));

const usableContentElement = (name) => {
  const value = name.replace(/\s+/g, " ").trim();
  if (value.length < 2 || value.length > 32) return false;
  if (/(?:의|에서|에는|을|를|이|가|와|과|된|하는|하여|하고|사는|생물에)$/.test(value)) return false;
  if (/(?:하기|자료를|문제를|가설을|활용하여|이끌어내기|나타내고|구하기|설정하기|적용하기)/.test(value)) return false;
  return !new Set(["관찰", "측정", "분류", "예상", "추리"]).has(value);
};

const officialTopics = (courseId) => {
  const seen = new Set();
  return (officialByCourse.get(courseId) ?? [])
    .flatMap((item) => item.name.split("⋅").map((name) => ({ ...item, name: name.trim() })))
    .filter((item) => usableContentElement(item.name))
    .filter((item) => {
      const key = item.name.replace(/\s+/g, "");
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .map((item) => ({
      name: item.name,
      domain: "지식·이해",
      sourceLabel: `NCIC · ${item.sourceId} · p.${item.page}`,
    }));
};

for (const level of ["middle", "high"]) {
  const courseCollection = readCollection(level, "courses");
  const domainCollection = readCollection(level, "domains");
  const standardCollection = readCollection(level, "standards");
  const groupCollection = readCollection(level, "subject-groups");
  const release = JSON.parse(readFileSync(resolve(sourceRoot, "data", "kr", level, "release.json"), "utf8"));
  const groups = new Map(groupCollection.records.map((group) => [group.id, group.labelKorean]));
  const domainNames = new Map(domainCollection.records.map((domain) => [domain.id, domain.labelKorean.replace(/\s+/g, " ").trim()]));
  const standardsByCourse = new Map();

  releases[level] = release.releaseId ?? courseCollection.releaseId;

  for (const standard of standardCollection.records) {
    if (!standard.summary) continue;
    const items = standardsByCourse.get(standard.courseId) ?? [];
    items.push(standard);
    standardsByCourse.set(standard.courseId, items);
  }

  for (const course of courseCollection.records) {
    const standards = standardsByCourse.get(course.id) ?? [];
    if (standards.length === 0) continue;
    const official = officialTopics(course.id);
    const fallbackDomains = [...new Set(standards.map((standard) => domainNames.get(standard.domainId)).filter(Boolean))]
      .map((name) => ({ name, domain: "교육과정 영역", sourceLabel: "교육과정 영역" }));
    courses.push({
      id: course.id,
      level,
      subjectGroup: groups.get(course.subjectGroupId) ?? "기타",
      name: course.labelKorean,
      category: categoryLabels[course.courseCategory] ?? course.courseCategory,
      topics: official.length > 0 ? official : fallbackDomains,
    });
  }
}

courses.sort((a, b) =>
  a.level.localeCompare(b.level) ||
  collator.compare(a.subjectGroup, b.subjectGroup) ||
  collator.compare(a.name, b.name),
);

let sourceCommit = "unknown";
try {
  sourceCommit = execFileSync(
    "git",
    ["-c", `safe.directory=${sourceRoot.replaceAll("\\", "/")}`, "-C", sourceRoot, "rev-parse", "HEAD"],
    { encoding: "utf8" },
  ).trim();
} catch {
  // The release IDs still identify the imported dataset when Git metadata is unavailable.
}

const output = `// Generated by scripts/sync-curriculum.mjs. Do not edit by hand.\n` +
`export type CurriculumLevel = "middle" | "high";\n\n` +
`export type CurriculumCourse = {\n` +
`  id: string;\n` +
`  level: CurriculumLevel;\n` +
`  subjectGroup: string;\n` +
`  name: string;\n` +
`  category: string;\n` +
`  topics: Array<{\n` +
`    name: string;\n` +
`    domain: string;\n` +
`    sourceLabel: string;\n` +
`  }>;\n` +
`};\n\n` +
`export const CURRICULUM_SOURCE = ${JSON.stringify({
  repository: "https://github.com/DECK6/korean-secondary-learning-map",
  commit: sourceCommit,
  releases,
}, null, 2)} as const;\n\n` +
`export const CURRICULUM_COURSES: CurriculumCourse[] = ${JSON.stringify(courses, null, 2)};\n`;

writeFileSync(resolve("app", "curriculum-data.ts"), output, "utf8");
console.log(`Wrote ${courses.length} courses to app/curriculum-data.ts`);
console.log(`Used official NCIC content elements for ${courses.filter((course) => course.topics.some((topic) => topic.domain === "지식·이해")).length} courses`);
